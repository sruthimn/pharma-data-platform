SELECT
    BATCH_ID
    ,COUNT(*) AS TEST_COUNT
    ,SUM(CASE WHEN QUALITY_RESULT IN ('Fail','OOS') THEN 1 ELSE 0 END) AS FAILED_TEST_COUNT
    ,CASE WHEN FAILED_TEST_COUNT > 0 THEN TRUE ELSE FALSE END AS HAS_QUALITY_FAILURE
FROM {{ ref('fact_quality_test') }}
GROUP BY BATCH_ID